"""Generate the docs that must track the code, so they cannot go stale.

    python scripts/gen_docs.py          # write them
    python scripts/gen_docs.py --check  # exit 1 if any is out of date (CI)

Writes:
  docs/LLM_PROMPT.md                                      the copy-paste prompt for non-programmers (embeds _template.py)
  skills/manimater-components/references/catalog.md       the component menu for the Claude skill
  skills/manimater-components/references/component-template.py   a copy of the template, for the skill
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from manimate import registry  # noqa: E402
from manimate.components import load_all  # noqa: E402

TEMPLATE = ROOT / "manimate/components/community/_template.py"


def catalog_md() -> str:
    load_all()
    comps = registry.all_components()
    domains = sorted({c.domain for c in comps}, key=lambda d: (d != "general", d))
    out = [
        "# Component catalog",
        "",
        "Generated by `scripts/gen_docs.py` from the registry: do not edit by hand. "
        "For full parameter details and examples read `catalog.json` at the repository root.",
        "",
    ]
    for d in domains:
        out += [f"## {d}", "", "| Component | What it shows | Parameters |", "|---|---|---|"]
        for c in (x for x in comps if x.domain == d):
            desc = c.description.replace("|", "/")
            if len(desc) > 170:
                desc = desc[:167].rsplit(" ", 1)[0] + "..."
            params = ", ".join(f"`{k}`{'*' if p.required else ''}" for k, p in c.params.items())
            out.append(f"| `{c.name}` | {desc} | {params} |")
        out.append("")
    out.append("`*` = required parameter.")
    return "\n".join(out) + "\n"


def llm_prompt_md() -> str:
    load_all()
    comps = registry.all_components()
    existing = ", ".join(f"`{c.name}`" for c in comps)
    return f'''# The prompt to copy into an LLM

Copy **everything below the line** into Claude, ChatGPT, Gemini or any LLM, and replace the part in `[BRACKETS]` with what you
want to animate. Generated by `scripts/gen_docs.py`: do not edit by hand.

---

You are helping me contribute one animation component to **manimater-components**, an open-source library of
tested Manim (https://www.manim.community/) components. A component is one Python function that draws a single
animation; an AI picks components and fills in their parameters as JSON, so a component must be reusable for many topics.

**What I want:** [DESCRIBE THE ANIMATION IN PLAIN WORDS. For example: "show how binary addition with carries works, with
two numbers I can choose", or "a pendulum whose length I can change, with the period shown".]

**Who it is for:** [e.g. high-school students, university engineering students, a general audience]

Write ONE complete Python file, in a single ```python code block, following this template exactly (same imports, same
decorator, same style). Then write a SECOND ```python block with a small pytest file for any plain-Python logic you
wrote (skip it if there is none).

## Rules
1. One idea per component. Pick a short snake_case name that is not already taken. Existing names: {existing}.
2. At most 5 parameters. Each has a clear description (an AI reads it), a default or `required=True`, and a validator
   that returns a plain-English error message for bad input. Never crash on odd input: clamp, trim, or fall back.
3. The `example` dict must be valid and must render.
4. Put any maths, algorithm or layout logic in a plain Python function that does not use Manim, so it can be tested.
5. Use only `theme` colours (`theme.ACCENT`, `theme.GOOD`, ...). Never hex colours. Keep text short and plain.
6. Call `ctx.fit(...)` so nothing leaves the screen. Fade the finished picture in as a whole with one `FadeIn`, then
   animate the parts that carry the meaning. Spend the time you are given (`ctx.remaining`, `Ctx.beat`).
7. Use `ctx.play(...)` and `ctx.wait(...)`, never `scene.play`.
8. Pure drawing code only: no network, no files, no subprocesses, no `eval`/`exec`, no extra libraries beyond
   `manim`, `numpy` and the Python standard library.
9. Finish with a one-paragraph plain-English summary: what it teaches, the parameters, and the failure cases you handled
   (too many items, empty input, very long labels).

## The template (copy its structure)

```python
{TEMPLATE.read_text().rstrip()}
```
'''


FILES = {
    ROOT / "docs/LLM_PROMPT.md": llm_prompt_md,
    ROOT / "skills/manimater-components/references/catalog.md": catalog_md,
    ROOT / "skills/manimater-components/references/component-template.py": lambda: TEMPLATE.read_text(),
}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, make in FILES.items():
        want = make()
        have = path.read_text() if path.exists() else None
        if have != want:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(want)
    if check and stale:
        print("Out of date (run: python scripts/gen_docs.py):", *map(str, stale), sep="\n  ")
        return 1
    print("up to date" if check else f"wrote {len(stale)} file(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
